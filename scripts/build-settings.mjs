import { readdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(resolve(root, "packages/pguide-cli-core/package.json"));
const { Ajv } = require("ajv");
const standaloneCode = require("ajv/dist/standalone").default;
const compiler = new Ajv({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true, lines: true },
});
const validators = {};
const exports = {};
const descriptions = [];
for (const directory of (await readdir(resolve(root, "packages"))).sort()) {
  const packageRoot = resolve(root, "packages", directory);
  let metadata;
  try {
    metadata = JSON.parse(await readFile(resolve(packageRoot, "package.json"), "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") continue;
    throw error;
  }
  if (metadata.pguide?.settings === undefined) continue;
  const description = JSON.parse(
    await readFile(resolve(packageRoot, metadata.pguide.settings), "utf8"),
  );
  descriptions.push({ name: metadata.name, description });
  for (const [id, setting] of Object.entries(description.settings)) {
    const name = `setting${Object.keys(validators).length}`;
    compiler.addSchema(setting.schema, id);
    const validate = compiler.getSchema(id);
    if (validate.$async) throw new Error(`Settings schema ${id} must validate synchronously.`);
    if (Object.hasOwn(setting, "default") && !validate(setting.default))
      throw new Error(`Invalid static default for ${id}.`);
    validators[id] = name;
    exports[name] = id;
  }
}
const destination = resolve(root, "packages/pguide-cli-core/src/built-in-settings.ts");
const content = `// @ts-nocheck
// Generated by scripts/build-settings.mjs; edit each package's settings.json.
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
export const builtInSettings = ${JSON.stringify(descriptions, null, 2)};
${standaloneCode(compiler, exports)}
export const builtInValidators = {
${Object.entries(validators)
  .map(([id, name]) => `  ${JSON.stringify(id)}: ${name},`)
  .join("\n")}
};
`;
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== content)
    throw new Error("Built-in settings are stale. Run node scripts/build-settings.mjs.");
} else {
  await writeFile(destination, content);
}
