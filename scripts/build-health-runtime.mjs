import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { buildEvidenceRuntime } from "./build-evidence-runtime.mjs";

await buildEvidenceRuntime("objective-devbox-health");
const root = fileURLToPath(new URL("..", import.meta.url));
const destination = join(
  root,
  ".staging",
  "objective-devbox-health",
  "runtime",
  "health-check.mjs",
);
const result = await build({
  absWorkingDir: root,
  entryPoints: ["packages/objective-devbox-health/health-check.mjs"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  banner: { js: "// Generated by scripts/build-health-runtime.mjs. Do not edit." },
  write: false,
  plugins: [
    {
      name: "staged-evidence",
      setup(build) {
        build.onResolve({ filter: /runtime\/evidence\.mjs$/ }, () => ({
          path: join(root, ".staging", "objective-devbox-health", "runtime", "evidence.mjs"),
        }));
      },
    },
  ],
});
const text = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")).replaceAll("\r\n", "\n") !== text)
    throw new Error("Stale health transport runtime; run pnpm health:build.");
} else {
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, text);
}
