import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { buildEvidenceRuntime } from "./build-evidence-runtime.mjs";

await buildEvidenceRuntime("objective-devbox-health");

const root = fileURLToPath(new URL("../packages/objective-devbox-health/", import.meta.url));
const seen = new Set();
const imports = new Map();
const declarations = [];
async function visit(path) {
  if (seen.has(path)) return;
  seen.add(path);
  const source = ts.createSourceFile(path, await readFile(path, "utf8"), ts.ScriptTarget.Latest);
  for (const node of source.statements) {
    if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) {
      const specifier = node.moduleSpecifier?.text;
      if (specifier?.startsWith(".")) {
        await visit(join(dirname(path), specifier));
      } else if (ts.isImportDeclaration(node)) {
        const bindings = imports.get(specifier) ?? new Set();
        for (const binding of node.importClause.namedBindings.elements)
          bindings.add(binding.getText(source));
        imports.set(specifier, bindings);
      }
    }
  }
  for (const node of source.statements) {
    if (!ts.isImportDeclaration(node) && !ts.isExportDeclaration(node))
      declarations.push(node.getText(source));
  }
}
await visit(join(root, "health-check.mjs"));
const text = [
  "// Generated by scripts/build-health-runtime.mjs. Do not edit.",
  ...[...imports].map(
    ([module, bindings]) =>
      `import { ${[...bindings].join(", ")} } from ${JSON.stringify(module)};`,
  ),
  ...declarations,
  "",
].join("\n");
const destination = join(root, "runtime", "health-check.mjs");
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")).replaceAll("\r\n", "\n") !== text)
    throw new Error("Stale health transport runtime; run pnpm health:build.");
} else {
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, text);
}
