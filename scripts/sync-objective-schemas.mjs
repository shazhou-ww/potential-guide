import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const check = process.argv.includes("--check");
const { taskBundleSchema } = await import("../packages/task-protocol/dist/index.js");
const { taskBuildSchema } = await import("../packages/pguide-task-bundle/dist/authoring.js");
const { checkBuildSchema } = await import("../packages/check-sdk/dist/authoring.js");
const { probeBuildSchema, objectiveSchema } = await import(
  "../packages/probe-sdk/dist/authoring.js"
);
for (const [kind, schema, version = "v1"] of [
  ["task", taskBundleSchema],
  ["task-build", taskBuildSchema],
  ["check-build", checkBuildSchema, "v2"],
  ["probe-build", probeBuildSchema],
  ["probe-objective", objectiveSchema],
]) {
  const destination = new URL(`../schemas/artifacts/${kind}/${version}.json`, import.meta.url);
  const text = execFileSync(
    process.execPath,
    [
      createRequire(import.meta.url).resolve("@biomejs/biome/bin/biome"),
      "format",
      "--stdin-file-path=schema.json",
    ],
    {
      input: JSON.stringify({
        $schema: "https://json-schema.org/draft/2020-12/schema",
        $id: `https://shazhou-ww.github.io/potential-guide/schemas/artifacts/${kind}/${version}.json`,
        ...schema,
      }),
      encoding: "utf8",
    },
  );
  if (check) {
    if ((await readFile(destination, "utf8")).replaceAll("\r\n", "\n") !== text)
      throw new Error(`Artifact schema differs: ${kind}.`);
  } else {
    await mkdir(fileURLToPath(new URL(".", destination)), { recursive: true });
    await writeFile(destination, text);
  }
}
let embedded = "// Generated by scripts/sync-objective-schemas.mjs. Do not edit.\n";
for (const [format, version] of [
  ["objective", "v1"],
  ["objective", "v2"],
  ["objective", "v3"],
  ["objectives", "v1"],
  ["objective-artifact", "v1"],
]) {
  const source = new URL(`../schemas/${format}/${version}.json`, import.meta.url);
  const destination = new URL(
    `../packages/pilot-protocol/schemas/${format}/${version}.json`,
    import.meta.url,
  );
  const bytes = await readFile(source);
  if (!(format === "objective" && version !== "v3"))
    embedded += `export const ${format.replace("-artifact", "Artifact")}Schema = ${bytes.toString().trim()};\n`;
  if (check) {
    if (!bytes.equals(await readFile(destination)))
      throw new Error(`Offline schema differs from canonical source: ${format}/${version}.json`);
  } else {
    await mkdir(fileURLToPath(new URL(".", destination)), { recursive: true });
    await writeFile(destination, bytes);
  }
}
const definitions = new URL(
  "../packages/pilot-protocol/src/schema-definitions.ts",
  import.meta.url,
);
embedded = execFileSync(
  process.execPath,
  [
    createRequire(import.meta.url).resolve("@biomejs/biome/bin/biome"),
    "format",
    "--stdin-file-path=schema-definitions.ts",
  ],
  { input: embedded, encoding: "utf8" },
);
if (check) {
  if ((await readFile(definitions, "utf8")).replaceAll("\r\n", "\n") !== embedded)
    throw new Error("Embedded schema definitions are stale.");
} else {
  await writeFile(definitions, embedded);
}
