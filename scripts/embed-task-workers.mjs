import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { isBuiltin, createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const name = process.argv[2];
if (name !== "check-runtime-files") throw new Error("Select an owned task Worker package.");
const source = join(root, "packages", name, "src");
const generated = new Set(["worker-source.ts", "runtime-identity.ts"]);
const check = process.argv.includes("--check");
async function save(filename, value) {
  const text = execFileSync(
    process.execPath,
    [
      createRequire(import.meta.url).resolve("@biomejs/biome/bin/biome"),
      "format",
      "--stdin-file-path=generated.ts",
    ],
    { input: value, encoding: "utf8" },
  );
  const path = join(source, filename);
  if (check) {
    if ((await readFile(path, "utf8")).replaceAll("\r\n", "\n") !== text)
      throw new Error(`Stale embedded Worker source: ${name}/${filename}`);
  } else await writeFile(path, text);
}
const result = await build({
  entryPoints: [join(source, "worker.ts")],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node22",
  write: false,
  metafile: true,
  minify: true,
  legalComments: "eof",
  logLevel: "silent",
});
if (
  result.outputFiles.length !== 1 ||
  Object.values(result.metafile.outputs).some((output) =>
    output.imports.some((entry) => entry.external && !isBuiltin(entry.path)),
  )
)
  throw new Error("Embedded business Worker must contain all non-builtin code.");
const worker = result.outputFiles[0].text;
await save(
  "worker-source.ts",
  `// Generated by scripts/embed-task-workers.mjs. Do not edit.\nexport const workerSource = ${JSON.stringify(worker)};\n`,
);
const hash = createHash("sha256");
for (const filename of (await readdir(source))
  .filter((path) => path.endsWith(".ts") && !generated.has(path))
  .sort()) {
  hash
    .update(filename)
    .update("\0")
    .update(await readFile(join(source, filename)));
}
hash.update(worker);
await save(
  "runtime-identity.ts",
  `// Generated by scripts/embed-task-workers.mjs. Do not edit.\nexport const runtimeRevision = ${JSON.stringify(hash.digest("hex"))};\n`,
);
