import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = fileURLToPath(new URL("..", import.meta.url));
const destination = join(root, "packages", "objective-pguide-self-check", "runtime");
const checking = process.argv.includes("--check");
const header = "// Generated by scripts/build-self-check-runtime.mjs. Do not edit.\n";
const source = async (path) =>
  (await readFile(join(root, ...path.split("/")), "utf8")).replaceAll("\r\n", "\n");
const emit = async (name, content, typescript = false) => {
  const text =
    header +
    (typescript
      ? ts.transpileModule(content, {
          compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
        }).outputText
      : content);
  const path = join(destination, name);
  if (checking) {
    if ((await readFile(path, "utf8")).replaceAll("\r\n", "\n") !== text)
      throw new Error(`Stale self-check runtime: ${name}; run pnpm self-check:build.`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, text);
  }
};
