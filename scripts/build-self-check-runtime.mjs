for (const name of await readdir(join(root, "packages", "objective-pguide-setup", "src"))) {
  if (name.endsWith(".mjs")) {
    let text = await source(`packages/objective-pguide-setup/src/${name}`);
    if (name === "runner.mjs") {
      const ast = ts.createSourceFile(name, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
      let removed = 0;
      const transformed = ts.transform(ast, [
        (context) => {
          const visit = (node) => {
            if (
              ts.isIfStatement(node) &&
              ts.isIdentifier(node.expression) &&
              node.expression.text === "remote"
            ) {
              removed++;
              return node.elseStatement === undefined
                ? undefined
                : ts.visitNode(node.elseStatement, visit);
            }
            return ts.visitEachChild(node, visit, context);
          };
          return (node) => ts.visitNode(node, visit);
        },
      ]);
      if (removed !== 3) throw new Error("Local-only self-check extraction contract changed.");
      text = ts.createPrinter().printFile(transformed.transformed[0]);
      transformed.dispose();
    }
    await emit(`src/${name}`, text);
  }
}

