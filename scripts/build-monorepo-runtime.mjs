import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { buildEvidenceRuntime } from "./build-evidence-runtime.mjs";

await buildEvidenceRuntime("objective-monorepo-standard");

const root = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(
  new URL("../packages/objective-monorepo-standard/package.json", import.meta.url),
);
const { parse } = require("yaml");
const packageRoot = join(root, "packages", "objective-monorepo-standard");
const destination = join(
  root,
  ".staging",
  "objective-monorepo-standard",
  "runtime",
  "pilot-checker.cjs",
);
const result = await build({
  absWorkingDir: root,
  entryPoints: ["packages/objective-monorepo-standard/src/index.ts"],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node22",
  supported: { "template-literal": false },
  minify: true,
  legalComments: "eof",
  banner: { js: "// Generated by scripts/build-monorepo-runtime.mjs. Do not edit." },
  write: false,
  metafile: true,
  alias: {
    "@potential-guide/objective-pilot": join(
      root,
      "packages",
      "objective-pilot",
      "src",
      "index.ts",
    ),
  },
});
const text = result.outputFiles[0].text;
const licenses = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes("node_modules")) continue;
  let directory = dirname(join(root, input));
  while (directory !== dirname(directory)) {
    try {
      const manifest = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
      if (licenses.has(manifest.name)) break;
      let license;
      for (const name of ["LICENSE", "LICENSE.txt", "LICENSE.md", "license", "license.txt"]) {
        try {
          license = await readFile(join(directory, name), "utf8");
          break;
        } catch (error) {
          if (error.code !== "ENOENT") throw error;
        }
      }
      if (license === undefined) throw new Error(`Missing bundled license: ${manifest.name}`);
      licenses.set(manifest.name, `${manifest.name}@${manifest.version}\n\n${license.trim()}`);
      break;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      directory = dirname(directory);
    }
  }
}
const notices = `${[...licenses]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([, license]) => license)
  .join("\n\n---\n\n")}\n`;
const noticePath = join(root, ".staging", "objective-monorepo-standard", "THIRD_PARTY_NOTICES.txt");
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")).replaceAll("\r\n", "\n") !== text)
    throw new Error("Stale monorepo standalone runtime; run pnpm monorepo:build.");
  if (
    (await readFile(noticePath, "utf8")).replaceAll("\r\n", "\n") !==
    notices.replaceAll("\r\n", "\n")
  )
    throw new Error("Stale bundled license notices; run pnpm monorepo:build.");
} else {
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, text);
  await writeFile(noticePath, notices);
}
const { packageSubjectSchema, repositorySubjectSchema } = require(destination);
async function generated(path, content) {
  const destination = join(
    root,
    ".staging",
    path.startsWith("package-standard/")
      ? "objective-package-standard"
      : "objective-monorepo-standard",
    path.replace(/^package-standard\//, ""),
  );
  if (process.argv.includes("--check")) {
    if (
      (await readFile(destination, "utf8")).replaceAll("\r\n", "\n") !==
      content.replaceAll("\r\n", "\n")
    )
      throw new Error(`Stale monorepo resource ${path}; run pnpm monorepo:build.`);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
for (const [prefix, subjectSchema] of [
  ["", repositorySubjectSchema],
  ["package-standard/", packageSubjectSchema],
]) {
  const definition = await readFile(
    join(
      root,
      "packages",
      prefix ? "objective-package-standard" : "objective-monorepo-standard",
      "objective.yaml",
    ),
    "utf8",
  );
  const canonical = (value) =>
    value === null || typeof value !== "object"
      ? value
      : Array.isArray(value)
        ? value.map(canonical)
        : Object.fromEntries(
            Object.keys(value)
              .sort()
              .map((key) => [key, canonical(value[key])]),
          );
  if (
    JSON.stringify(canonical(parse(definition).subjectSchema)) !==
    JSON.stringify(canonical(subjectSchema))
  )
    throw new Error("Root objective.yaml subjectSchema disagrees with the checker input contract.");
  await generated(
    `${prefix}observation-inputs.json`,
    `{\n  "contract": "bounded-readonly-filesystem-v1",\n  "subjectRoot": ${prefix ? '["root"]' : '["context", "repo", "rootPath"]'}\n}\n`,
  );
  await generated(`${prefix}objective.yaml`, definition);
}
await generated("package-standard/runtime/pilot-checker.cjs", text);
await generated(
  "package-standard/runtime/evidence.mjs",
  await readFile(
    join(root, ".staging", "objective-monorepo-standard", "runtime", "evidence.mjs"),
    "utf8",
  ),
);
await generated(
  "package-standard/check.mjs",
  (await readFile(join(packageRoot, "check.mjs"), "utf8")).replaceAll(
    'scope = "repository"',
    'scope = "package"',
  ),
);
await generated("package-standard/THIRD_PARTY_NOTICES.txt", notices);
